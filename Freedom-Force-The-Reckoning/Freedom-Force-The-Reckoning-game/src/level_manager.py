# ─────────────────────────────────────────────────────────────────────────────
class PlatformTile(pygame.sprite.Sprite):
    def __init__(self, x, y, stage_idx=0):
        super().__init__()
        idx = min(stage_idx, len(STAGE_COLOURS) - 1)
        col = STAGE_COLOURS[idx]
        brd = STAGE_BORDER[idx]
        self.image = pygame.Surface((TILE, TILE))
        self.image.fill(col)
        pygame.draw.rect(self.image, brd, (0, 0, TILE, TILE), 3)
        pygame.draw.line(self.image,
                         tuple(min(255, c + 60) for c in col),
                         (2, 2), (TILE - 3, 2), 2)
        self.rect = self.image.get_rect(topleft=(x, y))
        self.is_ground = False


class DoorSprite(pygame.sprite.Sprite):
    def __init__(self, x, y, loader):
        super().__init__()
        self.image = loader.get("door").copy()
        font = pygame.font.SysFont(None, 18)
        self.image.blit(font.render("NEXT", True, (255, 255, 0)), (4, 2))
        self.rect = self.image.get_rect(bottomleft=(x, y + TILE))


# ─────────────────────────────────────────────────────────────────────────────
class Stage:
    def __init__(self, stage_index, loader, *_):
        self.index  = stage_index
        self.loader = loader
        self.timer  = float(STAGE_DURATION) if stage_index != 10 else float("inf")
        self._parse(STAGE_MAPS[stage_index], stage_index)

    def _parse(self, raw_map, idx):
        from enemy    import EnemyGroup
        from powerups import (ActivationOrb, AntiBomb, EnergySphere,
                              B2BombPickup, ArrowBombPickup, HaloBombPickup,
                              WeaponPickup, DamageX, AmmoPickup)

        self.platforms  = pygame.sprite.Group()
        self.enemies    = EnemyGroup()
        self.powerups   = pygame.sprite.Group()
        self.door_group = pygame.sprite.GroupSingle()

        num_rows   = len(raw_map)
        max_col    = max(len(r) for r in raw_map)
        ground_row = num_rows - 1      # ← last row = ground (is_ground=True)

        self.player_spawn = (0, (num_rows - 5) * TILE)  # default: above ground

        # ── Pass 1: tiles ─────────────────────────────────────────────
        for ri, row in enumerate(raw_map):
            row = row.ljust(max_col, '.')
            for ci, ch in enumerate(row):
                if ch == '#':
                    t = PlatformTile(ci * TILE, ri * TILE, idx)
                    t.is_ground = (ri == ground_row)
                    self.platforms.add(t)

        # ── Pass 2: entities ──────────────────────────────────────────
        for ri, row in enumerate(raw_map):
            row = row.ljust(max_col, '.')
            for ci, ch in enumerate(row):
                px, py = ci * TILE, ri * TILE
                cx, cy = px + TILE // 2, py + TILE // 2

                if   ch == 'P':
                    self.player_spawn = (px, py)
                elif ch == 'D':
                    self.door_group.add(DoorSprite(px, py, self.loader))
                elif ch == 'E':
                    self.enemies.add(
                        EnemyGroup.spawn(
                            px, py,
                            max(0, px - 5 * TILE),
                            px + 5 * TILE,
                            self.loader,
                        )
                    )
                elif ch == 'S': self.powerups.add(EnergySphere(cx, cy, self.loader))
                elif ch == 'A': self.powerups.add(AntiBomb(cx, cy, self.loader))
                elif ch == 'O': self.powerups.add(ActivationOrb(cx, cy))
                elif ch == 'B': self.powerups.add(B2BombPickup(cx, cy, self.loader))
                elif ch == 'R': self.powerups.add(ArrowBombPickup(cx, cy, self.loader))
                elif ch == 'H': self.powerups.add(HaloBombPickup(cx, cy, self.loader))
                elif ch == 'W': self.powerups.add(WeaponPickup(cx, cy))
                elif ch == 'X': self.powerups.add(DamageX(cx, cy))
                elif ch == 'M': self.powerups.add(AmmoPickup(cx, cy))

        self.width  = max_col * TILE
        self.height = num_rows * TILE

    def tick_timer(self, dt):
        if self.timer == float("inf"):
            return False
        self.timer -= dt
        return self.timer <= 0

    def destroy_all_ground(self):
        tiles = [t for t in self.platforms if t.is_ground]
        for t in tiles[: len(tiles) // 2]:
            t.kill()


# ─────────────────────────────────────────────────────────────────────────────
class LevelManager:
    def __init__(self, loader):
        self.loader        = loader
        self._stages       = [None] * TOTAL_STAGES
        self.current_index = 0
        self._load_stage(0)

    def _load_stage(self, idx):
        if self._stages[idx] is None:
            self._stages[idx] = Stage(idx, self.loader)

    @property
    def current(self):
        return self._stages[self.current_index]

    @property
    def is_boss_stage(self):
        return self.current_index == 10

    def advance(self):
        if self.current_index < TOTAL_STAGES - 1:
            self.current_index += 1
            self._load_stage(self.current_index)

    def reset_to_start(self):
        self._stages       = [None] * TOTAL_STAGES
        self.current_index = 0
        self._load_stage(0)