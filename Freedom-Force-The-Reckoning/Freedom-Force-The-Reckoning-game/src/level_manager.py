# ─────────────────────────────────────────────────────────────────────────────
def shuffle_stages(stage_maps):
    boss_stage    = stage_maps[-1]
    regular       = stage_maps[:-1]
    fixed_indexes = {4, 9}
    fixed_stages  = {i: regular[i] for i in fixed_indexes}
    other_stages  = [regular[i] for i in range(len(regular)) if i not in fixed_indexes]
    random.shuffle(other_stages)
    result, j = [], 0
    for i in range(len(regular)):
        if i in fixed_indexes:
            result.append(fixed_stages[i])
        else:
            result.append(other_stages[j]); j += 1
    result.append(boss_stage)
    return result


STAGE_MAPS   = shuffle_stages(STAGE_MAPS)
TOTAL_STAGES = len(STAGE_MAPS)


